/**
 * Searches the classical dictionary by raw word or candidate roots.
 */
export function lookupClassicalWord(rawWord: string): LexiconLookupResult {
  const clean = cleanLexiconQuery(rawWord);
  if (!clean) {
    return { found: false, query: rawWord, message: "لم يتم إدخال مفردة للبحث" };
  }

  const { normalized, candidateRoots } = extractCandidateRoots(clean);

  // 1. Direct match on normalized word
  if (CLASSICAL_LEXICON[normalized]) {
    const entry = CLASSICAL_LEXICON[normalized];
    return {
      found: true,
      query: clean,
      root: entry.root,
      entry,
    };
  }

  // 2. Direct match on candidate roots
  for (const root of candidateRoots) {
    if (CLASSICAL_LEXICON[root]) {
      const entry = CLASSICAL_LEXICON[root];
      return {
        found: true,
        query: clean,
        root: entry.root,
        entry,
        suggestedRoots: candidateRoots.filter((r) => r !== entry.root),
      };
    }
  }

  // 3. Reverse match: search entries whose relatedWords include the normalized term
  for (const [, entry] of Object.entries(CLASSICAL_LEXICON)) {
    if (entry.relatedWords?.some((w) => normalizeArabic(w) === normalized)) {
      return {
        found: true,
        query: clean,
        root: entry.root,
        entry,
      };
    }
  }

  // 4. Fallback root reconstruction if word is not in pre-indexed dictionary
  const primaryRoot = candidateRoots[0] || normalized.slice(0, 3);
  return {
    found: false,
    query: clean,
    root: primaryRoot,
    suggestedRoots: candidateRoots,
    message: `المفردة "${clean}" (جذرها المقدر: ${formatRootLetters(primaryRoot)}) غير مفهرسة حاليًا في المعجم التراثي المختصر. يمكنك تقييدها في كراسة الجلسة.`,
  };
}
